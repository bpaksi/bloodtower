import { cpSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { loadStoryCatalog } from "../../core/loadStories.ts";
import { lintBuildSet, lintPackRoot, lintPath } from "../../scripts/packLint.ts";
import { loadPackDir } from "../load.ts";
import { loadPackV2Dir } from "./load.ts";

const repoRoot = join(import.meta.dirname, "../../../../../../");
const packsV2 = join(repoRoot, "packs");
const basePack = join(packsV2, "base");
const testPack = join(packsV2, "test");

describe("pack format v2 lint", () => {
  it("loads the base content pack with 60 board spaces", () => {
    const result = loadPackV2Dir(basePack, packsV2);
    expect(result.ok).toBe(true);
    if (!result.ok || result.kind !== "base-content") return;
    expect(result.pack.heroes).toHaveLength(6);
    expect(result.pack.board.spaces).toHaveLength(60);
    expect(result.pack.quest_types.map((q) => q.id)).toEqual([
      "tomb",
      "cave",
      "encampment",
      "fortress",
      "ruins",
      "shrine",
    ]);
  });

  it("loads the Proving Grounds story against base content", () => {
    const result = loadPackV2Dir(testPack, packsV2);
    expect(result.ok).toBe(true);
    if (!result.ok || result.kind !== "story") return;
    expect(result.pack.day.move_roll).toEqual({ dice: "2d4", floor: 2, modifiers: false });
    expect(result.pack.start.assignments).toHaveLength(4);
    expect(result.base.pack_id).toBe("base");
  });

  it("passes pack:lint for packs/test", () => {
    const report = lintPath("packs/test", repoRoot);
    expect(report.exitCode).toBe(0);
    expect(report.lines[0]).toContain("OK test");
  });

  const tempPacksV2 = () => {
    const root = mkdtempSync(join(tmpdir(), "pack-v2-root-"));
    const storyDir = join(root, "test");
    cpSync(testPack, storyDir, { recursive: true });
    cpSync(basePack, join(root, "base"), { recursive: true });
    return { root, storyDir };
  };

  it("refuses an unknown manifest key (no code in packs)", () => {
    const { root, storyDir } = tempPacksV2();
    try {
      const manifest = join(storyDir, "pack.yaml");
      const text = readFileSync(manifest, "utf8");
      writeFileSync(manifest, `${text}\nrun: eval("hack")\n`);
      const result = loadPackV2Dir(storyDir, root);
      expect(result.ok).toBe(false);
      if (result.ok) return;
      expect(result.issues.some((item) => item.rule === "P2-1")).toBe(true);
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });

  it("refuses an effect outside the fixed set", () => {
    const { root, storyDir } = tempPacksV2();
    try {
      const manifest = join(storyDir, "pack.yaml");
      const text = readFileSync(manifest, "utf8").replace("kind: set-flag", "kind: run-script");
      writeFileSync(manifest, text);
      const result = loadPackV2Dir(storyDir, root);
      expect(result.ok).toBe(false);
      if (result.ok) return;
      expect(result.issues.some((item) => item.rule === "P2-1")).toBe(true);
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });

  it("loads a story that also has markdown notes with backticks", () => {
    const { root, storyDir } = tempPacksV2();
    try {
      writeFileSync(
        join(storyDir, "CONVERSION-NOTES.md"),
        "# Notes\n\n`script.yaml` is generated by `python3 scripts/dracula-pack-convert.py` from `a...\n",
      );
      const result = loadPackV2Dir(storyDir, root);
      expect(result.ok).toBe(true);
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });

  it("validates only pack.yaml when playable is false", () => {
    const { root, storyDir } = tempPacksV2();
    try {
      const manifest = join(storyDir, "pack.yaml");
      const text = readFileSync(manifest, "utf8").replace("playable: true", "playable: false");
      writeFileSync(manifest, text);
      writeFileSync(join(storyDir, "CONVERSION-NOTES.md"), "`script.yaml`\n");
      writeFileSync(join(storyDir, "script.yaml"), ":\n  - [\n");
      const result = loadPackV2Dir(storyDir, root);
      expect(result.ok).toBe(true);
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });

  it("refuses a stray file that is not markdown and not pack data", () => {
    const { root, storyDir } = tempPacksV2();
    try {
      writeFileSync(join(storyDir, "notes.txt"), "not a pack file");
      const result = loadPackV2Dir(storyDir, root);
      expect(result.ok).toBe(false);
      if (result.ok) return;
      expect(result.issues.some((item) => item.file === "notes.txt")).toBe(true);
      expect(result.issues.some((item) => item.message.includes("CONVERSION-NOTES"))).toBe(false);
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });

  const withAsset = (yaml: string) => {
    const { root, storyDir } = tempPacksV2();
    const manifest = join(storyDir, "pack.yaml");
    const text = readFileSync(manifest, "utf8").replace(/\nassets:[\s\S]*$/, `\n${yaml.trim()}\n`);
    writeFileSync(manifest, text);
    return { root, storyDir };
  };

  it("fails a non-placeholder still whose path is not on disk", () => {
    const { root, storyDir } = withAsset(`
assets:
  - {id: still.hall, type: still, target: storyboard, status: final, path: assets/missing-hall.png}
`);
    try {
      const result = loadPackV2Dir(storyDir, root);
      expect(result.ok).toBe(false);
      if (result.ok) return;
      expect(
        result.issues.some((item) => item.rule === "P2-2" && item.path.includes("still.hall")),
      ).toBe(true);
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });

  it("warns, and still loads, when a placeholder still has no file", () => {
    const { root, storyDir } = withAsset(`
assets:
  - {id: still.hall, type: still, target: storyboard, status: placeholder}
`);
    try {
      const result = loadPackV2Dir(storyDir, root);
      expect(result.ok).toBe(true);
      if (!result.ok) return;
      expect(result.warnings.some((item) => item.rule === "W-asset")).toBe(true);
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });

  it("fails a non-placeholder audio path that is not on disk", () => {
    const { root, storyDir } = withAsset(`
assets:
  - {id: vo.narrator, type: line, target: storyboard, status: final, path: audio/narrator.m4a}
`);
    try {
      const result = loadPackV2Dir(storyDir, root);
      expect(result.ok).toBe(false);
      if (result.ok) return;
      expect(
        result.issues.some((item) => item.rule === "P2-2" && item.file === "audio/narrator.m4a"),
      ).toBe(true);
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });

  it("loads a non-placeholder audio asset when the file is in the pack", () => {
    const { root, storyDir } = withAsset(`
assets:
  - {id: vo.narrator, type: line, target: storyboard, status: final, path: audio/narrator.m4a}
`);
    try {
      mkdirSync(join(storyDir, "audio"));
      writeFileSync(join(storyDir, "audio", "narrator.m4a"), "x");
      const result = loadPackV2Dir(storyDir, root);
      expect(result.ok).toBe(true);
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });

  it("reports a pack.yaml that starts with a backtick instead of dropping the door", () => {
    const root = mkdtempSync(join(tmpdir(), "pack-catalog-"));
    try {
      const broken = join(root, "test");
      cpSync(testPack, broken, { recursive: true });
      writeFileSync(join(broken, "pack.yaml"), "`not yaml\n");
      mkdirSync(join(root, "notes"));
      writeFileSync(
        join(root, "notes", "pack.yaml"),
        "pack_id: notes\ntitle: Notes\nversion: 0.1.0\nengine_min: 0.1.0\nplayable: false\n",
      );
      const catalog = loadStoryCatalog(root);
      expect(catalog.stories.map((story) => story.card.id)).toEqual(["notes"]);
      expect(catalog.stories[0]?.card.playable).toBe(false);
      expect(catalog.stories[0]?.card.cover).toBeNull();
      expect(catalog.issues.some((item) => item.file === "pack.yaml" && item.rule === "P2-1")).toBe(
        true,
      );
      expect(catalog.issues.some((item) => item.message.includes("format: 2"))).toBe(false);
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });

  it("does not report CONVERSION-NOTES when the host loads the repo packs", () => {
    const catalog = loadStoryCatalog(join(repoRoot, "packs"));
    expect(catalog.issues.filter((item) => item.file.includes("CONVERSION-NOTES"))).toEqual([]);
    const testStory = catalog.stories.find((story) => story.card.id === "test");
    const dracula = catalog.stories.find((story) => story.card.id === "dracula");
    expect(testStory?.card.playable).toBe(true);
    expect(testStory?.card.cover).toBeNull();
    expect(dracula?.card.playable).toBe(false);
    expect(dracula?.card.title).toBe("The Count of Vellmoor");
    expect(dracula?.card.players).toBeNull();
    expect(dracula?.card.cover).toBe("/packs/dracula/assets/cover.png");
    expect(testStory?.setup.map((step) => step.id)).toEqual([
      "seals-and-skulls",
      "lay-out-board",
      "place-heroes",
    ]);
    expect(testStory?.setup.map((step) => step.label)).toEqual([
      "Place the seals on the tower and load the skulls into the chute.",
      "Lay out the board and orient the kingdoms.",
      "Stand each hero on their start building.",
    ]);
  });

  it("lints every door under the configured packs folder", () => {
    const report = lintBuildSet(repoRoot);
    expect(report.exitCode).toBe(0);
    expect(report.lines.some((line) => line.startsWith("OK test "))).toBe(true);
    expect(report.lines.some((line) => line.startsWith("OK base "))).toBe(true);
    expect(report.lines.some((line) => line.startsWith("OK dracula "))).toBe(true);
  });

  it("fails the build walk when any door fails", () => {
    const root = mkdtempSync(join(tmpdir(), "pack-doors-"));
    try {
      const bad = join(root, "bad");
      mkdirSync(bad);
      writeFileSync(join(bad, "pack.yaml"), "format: 2\nkind: story\n");
      const report = lintPackRoot(root, repoRoot);
      expect(report.exitCode).not.toBe(0);
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });

  it("fails a metadata-only pack whose cover file is missing", () => {
    const dir = mkdtempSync(join(tmpdir(), "pack-cover-"));
    try {
      cpSync(join(repoRoot, "packs", "dracula"), dir, { recursive: true });
      rmSync(join(dir, "assets", "cover.png"));
      const result = loadPackDir(dir);
      expect(result.ok).toBe(false);
      if (result.ok) return;
      expect(result.issues.some((item) => item.rule === "V-2" && item.path === "cover")).toBe(true);
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it("refuses a flag read that is never set", () => {
    const { root, storyDir } = tempPacksV2();
    try {
      const manifest = join(storyDir, "pack.yaml");
      const text = readFileSync(manifest, "utf8").replace(
        "flag: proving-grounds-open",
        "flag: never-written",
      );
      writeFileSync(manifest, text);
      const result = loadPackV2Dir(storyDir, root);
      expect(result.ok).toBe(false);
      if (result.ok) return;
      expect(result.issues.some((item) => item.rule === "P2-3")).toBe(true);
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });
});
